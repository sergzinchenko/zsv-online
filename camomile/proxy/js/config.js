// Конфигурация локального прокси. Лежит рядом с proxy.js — правьте значения
// и просто перезапустите proxy.js, никаких переменных окружения не нужно.
module.exports = {
  // Интерфейс и порт, на которых прокси слушает запросы из браузера.
  // 127.0.0.1 = только этот компьютер.
  bindAddress: '127.0.0.1',
  port: 3000,

  // Адреса (origin), с которых открывается агент. ОБЯЗАТЕЛЬНО: только им
  // прокси разрешает сопряжение и запросы. Пусто — прокси не запустится
  // (кроме открытого режима pairing.required: false). Пример:
  //   allowedOrigins: ['https://agent.corp.local', 'http://127.0.0.1:5500'],
  allowedOrigins: [],

  // ---- Доступ к прокси: сопряжение с агентом ----
  // Каждый запрос несёт токен (заголовок X-Agent-Host-Token), который агент
  // получает один раз: в агенте Настройки → Локальный хост → «Сопрячь», затем
  // подтверждение на странице прокси.
  pairing: {
    // false — прежний открытый режим без токена.
    required: true,
    // Где хранить сопряжения (только хэши токенов). Пусто —
    // %LOCALAPPDATA%\proxy-sso\pairings.tsv (~/.proxy-sso в других ОС),
    // тот же файл, что у Java-версии. Удалите его, чтобы отозвать все.
    file: '',
  },

  // Допустимые значения заголовка Host сверх 127.0.0.1:порт и localhost:порт.
  // Нужны, только если bindAddress не петлевой.
  hostHeaders: [],

  // Разрешённые HTTP-методы. GET/HEAD тела не имеют, остальные поддерживаются полностью.
  allowedMethods: ['GET', 'POST', 'PUT', 'DELETE', 'PATCH', 'HEAD'],

  // Белый список хостов, куда прокси разрешено ходить (защита от SSRF —
  // без него любая страница, знающая порт прокси, может ходить куда угодно
  // от имени вашей локальной машины). Пустой массив = ограничений нет,
  // подходит только для локальной разработки.
  allowlist: [],

  // ---- Сеансы: cookie цели между запросами ----
  // Веб-приложения с входом и защитой от CSRF (Spring Security, GWT, Битрикс и
  // т. п.) связывают токен с cookie сеанса (JSESSIONID и др.). Браузер агента
  // cookie цели не хранит, поэтому прокси держит их сам: GET получил сеанс и
  // токен, POST с этим токеном идёт в тот же сеанс. Иначе приложение отвечает
  // «Could not verify the provided CSRF token because your session was not found».
  // Сеанс принадлежит агенту (токен сопряжения), серверу и учётке (заголовок
  // Authorization): сеанс одного не достаётся другому. Set-Cookie цели браузеру
  // не отдаётся; свой заголовок Cookie клиента идёт как есть.
  session: {
    // 'all' — для любых целей; 'off' — каждый запрос без cookie, как раньше.
    cookies: 'all',
    // Через сколько секунд без запросов сеанс забывается.
    idleSec: 900,
    // Изменяющему запросу без своего X-XSRF-TOKEN или X-CSRF-TOKEN прокси
    // добавляет X-XSRF-TOKEN со значением cookie XSRF-TOKEN сеанса (так делают
    // браузерные приложения на Angular и Spring CookieCsrfTokenRepository).
    xsrfCookie: true,
  },

  // Максимальный размер тела входящего запроса от браузера, в байтах.
  maxRequestBodyBytes: 10 * 1024 * 1024, // 10 MB

  // Сколько байт тела запроса/ответа печатать в консоль при логировании
  // (пересылка клиенту при этом всегда идёт полностью, лимит только для лога).
  maxLogBytes: 4096,

  // Отключить цветной (ANSI) вывод в консоли — удобно, если логи пишутся в файл.
  noColor: false,

  // ---- TLS: доверие к сертификатам целевых серверов ----
  // Внутренние (корпоративные) серверы обычно выпускают сертификаты своим
  // удостоверяющим центром, которого нет в списке доверенных у Node. Без
  // настройки такой запрос падает, и прокси отвечает 502.
  //
  // Варианты перечислены от правильного к крайнему — берите первый, который
  // применим.
  tls: {
    // 1. ЛУЧШИЙ ВАРИАНТ. Путь к PEM-файлу с сертификатом вашего
    //    удостоверяющего центра (можно несколько, склеенных подряд).
    //    Проверка при этом ОСТАЁТСЯ включённой: подменённый сертификат
    //    по-прежнему будет отвергнут, просто теперь Node знает ваш CA.
    //    Путь абсолютный или относительно папки с proxy.js.
    caFile: '',

    // 2. КОМПРОМИСС. Не проверять сертификаты только у этих хостов.
    //    'corp.local' покрывает и 'intranet.corp.local'. Годится, когда
    //    до CA-файла не добраться, а ходить нужно на один-два адреса.
    insecureHosts: [],

    // 3. КРАЙНИЙ СЛУЧАЙ. Не проверять сертификаты вообще ни у кого.
    //    Это отключает защиту от подмены сервера на ВСЕХ адресах, включая
    //    внешние: перехватчик трафика станет неотличим от настоящего
    //    сервера. Держите включённым только на время разбирательства.
    insecure: false,
  },

  // SSO (вход под учётной записью Windows) есть только в Java-версии
  // прокси (proxy-sso.jar). Запрос с ?sso=1 получает здесь ответ 501.
};
